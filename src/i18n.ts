export function t(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  let s: string = STR[lang]?.[key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}
