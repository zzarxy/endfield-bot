// UI strings in every supported language. English is the source; the other dictionaries are typed
// against it, so a missing key is a compile error. Translations have not been reviewed by native speakers.
export type Lang = "en" | "ru" | "uk" | "es" | "ja" | "ko" | "zh" | "tc";
export const LANGS: Lang[] = ["en", "ru", "uk", "es", "ja", "ko", "zh", "tc"];

/** Languages that have game names on the wiki (Locales table), mapped to the wiki's own language codes. */
export const WIKI_LANG: Partial<Record<Lang, string>> = { ru: "ru", es: "sp", ja: "jp", ko: "kr", zh: "cn", tc: "tc" };

/** Discord locale codes used for slash command descriptions. */
export const DISCORD_LOCALES: Record<Exclude<Lang, "en">, string[]> = {
  ru: ["ru"], uk: ["uk"], es: ["es-ES", "es-419"], ja: ["ja"], ko: ["ko"], zh: ["zh-CN"], tc: ["zh-TW"],
};

export const LANG_LABEL: Record<Lang, string> = {
  en: "English", ru: "Русский", uk: "Українська", es: "Español", ja: "日本語", ko: "한국어", zh: "简体中文", tc: "繁體中文",
};

export function localeToLang(locale?: string | null): Lang {
  const l = (locale ?? "").toLowerCase();
  if (l === "zh-tw") return "tc";
  if (l.startsWith("zh")) return "zh";
  const base = l.split("-")[0];
  return (LANGS as string[]).includes(base) ? (base as Lang) : "en";
}

